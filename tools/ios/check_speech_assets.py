#!/usr/bin/env python3
"""Keeps tools/speech-assets.json in step with `speechAssets` in app/build.gradle.kts.

The Android build is the source of truth for the bundled ru/en/tr models (URL + SHA-256). The iOS "full" build
downloads the same files with ios/scripts/fetch-speech-models.sh, which reads the JSON.

  check_speech_assets.py          fail (exit 1) when the JSON drifted from the Gradle file
  check_speech_assets.py --write  regenerate the JSON from the Gradle file
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GRADLE = ROOT / "app" / "build.gradle.kts"
JSON_PATH = ROOT / "tools" / "speech-assets.json"
ANDROID_PREFIX = "src/main/assets/"
IOS_PREFIX = "ios/Suflyor/Models/"

STRING = r'"((?:[^"\\]|\\.)*)"'


def gradle_vals(text: str) -> dict[str, str]:
    """`private val name =\\n "literal"` string constants (the model base URLs)."""
    out: dict[str, str] = {}
    for m in re.finditer(r"(?m)^\s*(?:private\s+)?val\s+(\w+)\s*=\s*" + STRING, text):
        out[m.group(1)] = m.group(2)
    return out


def expand(literal: str, vals: dict[str, str]) -> str:
    def sub(m: re.Match[str]) -> str:
        name = m.group(1) or m.group(2)
        if name not in vals:
            raise SystemExit(f"unknown Kotlin variable ${name} in {GRADLE}")
        return vals[name]

    return re.sub(r"\$\{(\w+)\}|\$(\w+)", sub, literal)


def parse_gradle(text: str) -> list[dict[str, str]]:
    vals = gradle_vals(text)
    start = text.find("val speechAssets")
    if start < 0:
        raise SystemExit("speechAssets not found in app/build.gradle.kts")
    # The list ends at the closing paren in column 0.
    end = text.find("\n)\n", start)
    block = text[start:end if end > 0 else len(text)]
    block = re.sub(r"(?m)^\s*//.*$", "", block)  # comments between entries
    entries = []
    for m in re.finditer(r"Triple\(\s*" + STRING + r"\s*,\s*" + STRING + r"\s*,\s*" + STRING + r"\s*,?\s*\)", block):
        path, url, sha = m.group(1), expand(m.group(2), vals), m.group(3)
        if not path.startswith(ANDROID_PREFIX):
            continue  # the sherpa-onnx .aar is Android only (iOS uses the XCFramework)
        rel = path[len(ANDROID_PREFIX):]  # asr-ru/encoder.int8.onnx
        entries.append({"path": IOS_PREFIX + rel, "url": url, "sha256": sha})
    if not entries:
        raise SystemExit("no model entries parsed from speechAssets")
    for e in entries:
        if not re.fullmatch(r"[0-9a-f]{64}", e["sha256"]):
            raise SystemExit(f"bad SHA-256 for {e['path']}")
    return entries


def render(entries: list[dict[str, str]]) -> str:
    doc = {
        "_comment": "Generated by tools/ios/check_speech_assets.py --write from app/build.gradle.kts (speechAssets, "
                    "without the .aar). Do not edit by hand.",
        "version": 1,
        "assets": entries,
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="regenerate tools/speech-assets.json")
    args = ap.parse_args()
    expected = render(parse_gradle(GRADLE.read_text(encoding="utf-8")))
    if args.write:
        JSON_PATH.write_text(expected, encoding="utf-8")
        print(f"wrote {JSON_PATH.relative_to(ROOT)}")
        return 0
    if not JSON_PATH.exists():
        print(f"{JSON_PATH.relative_to(ROOT)} is missing; run with --write", file=sys.stderr)
        return 1
    actual = JSON_PATH.read_text(encoding="utf-8")
    if actual != expected:
        try:
            a = {e["path"]: e for e in json.loads(actual)["assets"]}
        except (ValueError, KeyError):
            a = {}
        e = {x["path"]: x for x in json.loads(expected)["assets"]}
        for p in sorted(set(a) | set(e)):
            if a.get(p) != e.get(p):
                print(f"drift: {p}\n  json:   {a.get(p)}\n  gradle: {e.get(p)}", file=sys.stderr)
        print("tools/speech-assets.json is stale; run: python3 tools/ios/check_speech_assets.py --write", file=sys.stderr)
        return 1
    print(f"ok: {len(json.loads(actual)['assets'])} speech assets match app/build.gradle.kts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
