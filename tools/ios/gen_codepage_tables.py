import sys

names = {
    'windows1250': 'cp1250', 'windows1251': 'cp1251', 'windows1252': 'cp1252', 'windows1253': 'cp1253',
    'windows1254': 'cp1254', 'windows1255': 'cp1255', 'windows1256': 'cp1256', 'windows1257': 'cp1257',
    'windows1258': 'cp1258', 'windows874': 'cp874', 'koi8r': 'koi8_r',
}
out = []
out.append("""import Foundation

/// Single-byte code pages decoded with built-in tables (bytes 0x80...0xFF), the way Java's charsets do: undefined
/// bytes become U+FFFD. Own tables keep the result identical to Android and independent of Foundation's converters
/// (whose handling of undefined bytes is not guaranteed). Generated by tools/ios/gen_codepage_tables.py (Python codecs); do not edit
/// 0x00...0x7F are ASCII in all of them.
enum SingleByteCodepage {
    case windows1250, windows1251, windows1252, windows1253, windows1254, windows1255, windows1256, windows1257
    case windows1258, windows874, koi8r

    func decode(_ bytes: some Sequence<UInt8>) -> String {
        let table = self.table
        var units: [UInt16] = []
        for b in bytes {
            units.append(b < 0x80 ? UInt16(b) : table[Int(b) - 0x80])
        }
        return String(decoding: units, as: UTF16.self)
    }

    private var table: [UInt16] {
        switch self {
        case .windows1250: Self.windows1250Table
        case .windows1251: Self.windows1251Table
        case .windows1252: Self.windows1252Table
        case .windows1253: Self.windows1253Table
        case .windows1254: Self.windows1254Table
        case .windows1255: Self.windows1255Table
        case .windows1256: Self.windows1256Table
        case .windows1257: Self.windows1257Table
        case .windows1258: Self.windows1258Table
        case .windows874: Self.windows874Table
        case .koi8r: Self.koi8rTable
        }
    }
""")
for n, c in names.items():
    row = []
    for b in range(0x80, 0x100):
        try:
            ch = bytes([b]).decode(c)
        except UnicodeDecodeError:
            ch = '�'
        assert len(ch) == 1
        row.append(ord(ch))
    out.append(f"\n    private static let {n}Table: [UInt16] = [")
    for k in range(0, 128, 8):
        out.append("        " + ", ".join(f"0x{v:04X}" for v in row[k:k + 8]) + ",")
    out.append("    ]")
out.append("}\n")
open(sys.argv[1], "w", encoding="utf-8").write("\n".join(out))
