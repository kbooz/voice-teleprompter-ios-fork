#!/usr/bin/env python3
"""Keeps the iOS speech-pack catalog identical to Android's.

Reads app/src/main/java/com/olerast/suflyor/speech/SpeechPackCatalog.kt (written by tools/speech-packs/build.py) and
writes ios/Packages/SuflyorKit/Sources/SuflyorSpeech/SpeechPackCatalog.swift: same files, sizes and SHA-256.

  python3 ios/scripts/speech_pack_catalog.py            regenerate the Swift file
  python3 ios/scripts/speech_pack_catalog.py --check    exit 1 when the Swift file does not match the Kotlin one
"""
import argparse
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
KOTLIN = os.path.join(ROOT, 'app/src/main/java/com/olerast/suflyor/speech/SpeechPackCatalog.kt')
SWIFT = os.path.join(ROOT, 'ios/Packages/SuflyorKit/Sources/SuflyorSpeech/SpeechPackCatalog.swift')

ENTRY = re.compile(
    r'SpeechPack\(SpeechLang\.(\w+),\s*(\d+),\s*"([^"]+)",\s*(\d+)L,\s*"([0-9a-f]{64})",\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)"\)'
)
SWIFT_ENTRY = re.compile(
    r'SpeechPackInfo\(\s*language: \.(\w+),\s*version: (\d+),\s*fileName: "([^"]+)",\s*bytes: (\d+),\s*'
    r'sha256: "([0-9a-f]{64})",\s*model: "([^"]+)",\s*license: "([^"]+)",\s*releaseTag: "([^"]+)"\s*\)'
)


def kotlin_entries():
    text = open(KOTLIN, encoding='utf-8').read()
    entries = [(m.group(1).lower(), int(m.group(2)), m.group(3), int(m.group(4)), m.group(5), m.group(6), m.group(7),
                m.group(8)) for m in ENTRY.finditer(text)]
    if text.count('SpeechPack(SpeechLang.') != len(entries):
        sys.exit('SpeechPackCatalog.kt has an entry this script cannot parse')
    return entries


def render(entries):
    lines = [
        '// Generated by ios/scripts/speech_pack_catalog.py from the Android SpeechPackCatalog.kt: do not edit by hand.',
        '// The same zip files, sizes and SHA-256 as Android, so a pack works on both apps.',
        'import SuflyorDomain',
        '',
        'enum SpeechPackCatalog {',
        '    static let packs: [SpeechPackInfo] = [',
    ]
    for lang, version, name, size, sha, model, lic, tag in entries:
        lines += [
            '        SpeechPackInfo(',
            f'            language: .{lang}, version: {version}, fileName: "{name}", bytes: {size},',
            f'            sha256: "{sha}",',
            f'            model: "{model}", license: "{lic}", releaseTag: "{tag}"',
            '        ),',
        ]
    lines += ['    ]', '}', '']
    return '\n'.join(lines)


def swift_entries():
    text = open(SWIFT, encoding='utf-8').read()
    return [(m.group(1), int(m.group(2)), m.group(3), int(m.group(4)), m.group(5), m.group(6), m.group(7), m.group(8))
            for m in SWIFT_ENTRY.finditer(text)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    entries = kotlin_entries()
    if args.check:
        found = swift_entries()
        if found != entries:
            print(f'MISMATCH: Kotlin has {len(entries)} packs, Swift {len(found)} (or the contents differ)')
            for a, b in zip(entries, found):
                if a != b:
                    print('  kotlin:', a)
                    print('  swift: ', b)
            sys.exit(1)
        print(f'OK: {len(entries)} packs, identical in Kotlin and Swift (files, sizes, SHA-256, models, licenses, releases)')
        return
    with open(SWIFT, 'w', encoding='utf-8') as f:
        f.write(render(entries))
    print(f'Wrote {len(entries)} packs to {os.path.relpath(SWIFT, ROOT)}')


if __name__ == '__main__':
    main()
