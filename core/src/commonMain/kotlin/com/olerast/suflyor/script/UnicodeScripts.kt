        0x1D78, 0x1D79, 0x1E00, 0x2071, 0x207F, 0x2090, 0x212A, 0x2132, 0x214E, 0x2160, 0x2C60, 0x2DE0, 0x2E80,
        0x3005, 0x3007, 0x3021, 0x302E, 0x3038, 0x3131, 0x3200, 0x3260, 0x3400, 0x4E00, 0xA640, 0xA722, 0xA78B,
