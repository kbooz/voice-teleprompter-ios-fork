package com.olerast.suflyor.script

/** The scripts the tracker tells apart; everything else is [OTHER]. */
enum class UScript { LATIN, CYRILLIC, HAN, HANGUL, HEBREW, ARABIC, OTHER }

/**
 * Script of a code point, for common code (java.lang.Character.UnicodeScript is JVM only). The table was generated
 * from the JDK 21 data (Unicode 15) and a jvmTest compares it with Character.UnicodeScript.of for every code point.
 * Unassigned code points inside a range count as that script, so a newer Unicode version needs no table change.
 */
object UnicodeScripts {
    private val STARTS = intArrayOf(
        0x41, 0x61, 0xAA, 0xBA, 0xC0, 0xD8, 0xF8, 0x2E0, 0x400, 0x487, 0x591, 0x600, 0x606, 0x60D, 0x61C, 0x620,
